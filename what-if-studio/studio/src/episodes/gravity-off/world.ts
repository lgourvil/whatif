const lerp = (a: number, b: number, t: number) => a + (b - a) * t;

/** Plaza (flat) -> grassy hills behind, sea bowl in front (z < -70), cliffs left/right. */
export const groundH = (x: number, z: number): number => {
  let h = 0.15 + Math.sin(x * 0.08 + z * 0.06) * 0.25;
  const hills = smoothstep(30, 110, z) * (6 + Math.sin(x * 0.05) * 5);
  const sides = smoothstep(70, 150, Math.abs(x)) * 22;
  h += hills + sides;
  const bowl = smoothstep(-52, -90, z);
  h = lerp(h, -12, bowl);
  return h;
};
